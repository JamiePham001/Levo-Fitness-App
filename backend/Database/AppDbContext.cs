using backend.Entities;
using backend.Entities.ExerciseSets;
using backend.Entities.Exercises;
using backend.Entities.Friendships;
using backend.Entities.Goals;
using backend.Entities.Movements;
using backend.Entities.Notifications;
using backend.Entities.ProgramBlocks;
using backend.Entities.Programs;
using backend.Entities.ProgramShares;
using backend.Entities.Users;
using backend.Entities.Workouts;
using Microsoft.EntityFrameworkCore;

namespace backend.Database;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<User> Users => Set<User>();
    public DbSet<Goal> Goals => Set<Goal>();
    public DbSet<Movement> Movements => Set<Movement>();
    public DbSet<TrainingProgram> Programs => Set<TrainingProgram>();
    public DbSet<ProgramBlock> ProgramBlocks => Set<ProgramBlock>();
    public DbSet<Workout> Workouts => Set<Workout>();
    public DbSet<Exercise> Exercises => Set<Exercise>();
    public DbSet<ExerciseSet> ExerciseSets => Set<ExerciseSet>();
    public DbSet<Friendship> Friendships => Set<Friendship>();
    public DbSet<ProgramShare> ProgramShares => Set<ProgramShare>();
    public DbSet<Notification> Notifications => Set<Notification>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Case-insensitive text so "Sam" and "sam" cannot both register.
        modelBuilder.HasPostgresExtension("citext");

        modelBuilder.Entity<User>(e =>
        {
            // Id is the Supabase auth.users.id, never generated by the database.
            e.HasKey(u => u.Id);
            e.Property(u => u.Id).ValueGeneratedNever();
            e.Property(u => u.Username).HasColumnType("citext").IsRequired();
            e.Property(u => u.Email).HasColumnType("citext").IsRequired();
            e.Property(u => u.AvatarUrl).HasMaxLength(2048);
            e.Property(u => u.Provider).HasMaxLength(20);
            e.Property(u => u.Gender).HasConversion<string>().HasMaxLength(10);
            e.Property(u => u.Role).HasConversion<string>().HasMaxLength(10);
            e.Property(u => u.Measurement).HasConversion<string>().HasMaxLength(10);
            e.HasIndex(u => u.Username).IsUnique();
        });

        // Synced entities: client-generated ids, an owning user, and the pull and purge indexes.
        ConfigureSyncEntity<Goal>(modelBuilder);
        ConfigureSyncEntity<Movement>(modelBuilder);
        ConfigureSyncEntity<TrainingProgram>(modelBuilder);
        ConfigureSyncEntity<ProgramBlock>(modelBuilder);
        ConfigureSyncEntity<Workout>(modelBuilder);
        ConfigureSyncEntity<Exercise>(modelBuilder);
        ConfigureSyncEntity<ExerciseSet>(modelBuilder);

        modelBuilder.Entity<Goal>(e =>
        {
            e.Property(g => g.Name).HasMaxLength(100).IsRequired();
            e.Property(g => g.Level).HasConversion<string>().HasMaxLength(20);
        });

        modelBuilder.Entity<Movement>(e =>
        {
            e.Property(m => m.Name).HasMaxLength(100).IsRequired();
        });

        modelBuilder.Entity<TrainingProgram>(e =>
        {
            e.Property(p => p.Name).HasMaxLength(100).IsRequired();
            e.Property(p => p.Type).HasConversion<string>().HasMaxLength(20);
        });

        modelBuilder.Entity<ProgramBlock>(e =>
        {
            e.Property(b => b.Name).HasMaxLength(100);
            e.HasOne<TrainingProgram>().WithMany().HasForeignKey(b => b.ProgramId).OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<Workout>(e =>
        {
            e.Property(w => w.Name).HasMaxLength(100);
            e.HasOne<ProgramBlock>().WithMany().HasForeignKey(w => w.BlockId).OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<Exercise>(e =>
        {
            e.Property(x => x.Name).HasMaxLength(100).IsRequired();
            e.Property(x => x.Notes).HasMaxLength(2000);
            e.HasOne<Workout>().WithMany().HasForeignKey(x => x.WorkoutId).OnDelete(DeleteBehavior.Cascade);
            // MovementId is deliberately not a foreign key: see Exercise.MovementId.
        });

        modelBuilder.Entity<ExerciseSet>(e =>
        {
            e.HasOne<Exercise>().WithMany().HasForeignKey(s => s.ExerciseId).OnDelete(DeleteBehavior.Cascade);
        });

        // Online-only entities.
        modelBuilder.Entity<Friendship>(e =>
        {
            e.HasKey(f => f.Id);
            e.Property(f => f.Id).ValueGeneratedNever();
            e.Property(f => f.Status).HasConversion<string>().HasMaxLength(10);
            e.HasOne<User>().WithMany().HasForeignKey(f => f.RequesterId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<User>().WithMany().HasForeignKey(f => f.ReceiverId).OnDelete(DeleteBehavior.Cascade);
            e.HasIndex(f => f.RequesterId);
            e.HasIndex(f => f.ReceiverId);
            // One friendship per pair in either direction: a unique expression index on
            // (LEAST(requester, receiver), GREATEST(...)) is created in the AddRemainingEntities migration.
        });

        modelBuilder.Entity<ProgramShare>(e =>
        {
            e.HasKey(s => s.Id);
            e.Property(s => s.Id).ValueGeneratedNever();
            e.Property(s => s.Access).HasConversion<string>().HasMaxLength(10);
            e.HasOne<TrainingProgram>().WithMany().HasForeignKey(s => s.ProgramId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<User>().WithMany().HasForeignKey(s => s.ReceiverId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<User>().WithMany().HasForeignKey(s => s.SenderId).OnDelete(DeleteBehavior.Cascade);
            e.HasIndex(s => new { s.ProgramId, s.ReceiverId }).IsUnique();
            e.HasIndex(s => s.ReceiverId);
        });

        modelBuilder.Entity<Notification>(e =>
        {
            e.HasKey(n => n.Id);
            e.Property(n => n.Id).ValueGeneratedNever();
            e.Property(n => n.Type).HasConversion<string>().HasMaxLength(30);
            e.HasOne<User>().WithMany().HasForeignKey(n => n.ReceiverId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<User>().WithMany().HasForeignKey(n => n.SenderId).OnDelete(DeleteBehavior.Cascade);
            // Inbox listing, newest first.
            e.HasIndex(n => new { n.ReceiverId, n.CreatedAt });
            // Unread badge: only unread rows are indexed.
            e.HasIndex(n => n.ReceiverId).HasFilter("\"ReadAt\" IS NULL").HasDatabaseName("IX_Notifications_ReceiverId_Unread");
            // A retried request cannot create a duplicate notification.
            e.HasIndex(n => new { n.ReceiverId, n.Type, n.TargetId }).IsUnique();
        });
    }

    private static void ConfigureSyncEntity<T>(ModelBuilder modelBuilder) where T : SyncEntity
    {
        var e = modelBuilder.Entity<T>();
        // Id is client-generated so records can be created offline.
        e.HasKey("Id");
        e.Property<Guid>("Id").ValueGeneratedNever();
        e.HasOne<User>().WithMany().HasForeignKey("UserId").OnDelete(DeleteBehavior.Cascade);
        // Sync pull: rows for a user changed since the cursor.
        e.HasIndex("UserId", nameof(SyncEntity.ServerUpdateAt));
        // Tombstone purge on sync: only the deleted rows are indexed.
        e.HasIndex("UserId", nameof(SyncEntity.DeletedAt)).HasFilter("\"DeletedAt\" IS NOT NULL");
    }
}
